"""Writes the Android app's protocol constants and its test vectors from the desktop code.

Run from the project folder:  py tools/android_vectors.py

It writes two files, both from the Python code the PC and the Deck already run:
  android/app/src/main/java/com/joycon2studio/Generated.kt   the Joy-Con 2 UUIDs, commands and link constants
  android/app/src/test/resources/vectors.json                 inputs and outputs the Android tests check against

The Android app therefore cannot drift from the desktop code without this script being run again.
"""
import hashlib
import json
import pathlib
import random
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "decky" / "joycon2studio"))

import joycon2_gui as g  # noqa: E402  (imports bleak; the PC app needs it anyway)
import joycon2_link as link  # noqa: E402

KOTLIN_OUT = ROOT / "android" / "app" / "src" / "main" / "java" / "com" / "joycon2studio" / "Generated.kt"
VECTOR_OUT = ROOT / "android" / "app" / "src" / "test" / "resources" / "vectors.json"
PIN = "042917"


def scalar(label: bytes) -> int:
    return int.from_bytes(hashlib.sha256(label).digest(), "big") % link.L


def hexof(data: bytes) -> str:
    return bytes(data).hex()


def int_hex(value: int, size: int) -> str:
    return value.to_bytes(size, "big").hex()


# ---- desktop helpers that need no GUI state ------------------------------------------------

class _Fake:
    """Stands in for the parts of JoyCon2Manager that a function calls but that do not affect its result."""


def parse_input(side: str, data: bytes):
    """Runs the desktop's own _parse_input_report on a fresh Joy-Con state and returns that state."""
    manager = _Fake()
    for name in ("_update_mode", "_update_active_side", "_move_cursor", "_mouse_clicks", "_sync_virtual_gamepad"):
        setattr(manager, name, lambda *a, **k: None)
    state = g.JoyConState(side)
    g.JoyCon2Manager._parse_input_report(manager, state, bytearray(data))
    return state


def bridge_report(left, right) -> bytes:
    """Runs the desktop's own _bridge_report on the two states."""
    manager = _Fake()
    manager.left = left
    manager.right = right
    manager._norm_axis = lambda raw, center, deadzone=140, span=1750.0: g.JoyCon2Manager._norm_axis(
        None, raw, center, deadzone, span)
    return g.JoyCon2Manager._bridge_report(manager)


# ---- Generated.kt ----------------------------------------------------------------------------

BUTTONS = ["BTN_Y", "BTN_X", "BTN_B", "BTN_A", "BTN_SR_R", "BTN_SL_R", "BTN_R", "BTN_ZR", "BTN_MINUS",
           "BTN_PLUS", "BTN_R3", "BTN_L3", "BTN_HOME", "BTN_CAPTURE", "BTN_DOWN", "BTN_UP", "BTN_RIGHT",
           "BTN_LEFT", "BTN_SR_L", "BTN_SL_L", "BTN_L", "BTN_ZL"]


def write_kotlin() -> None:
    lines = [
        "// Generated by tools/android_vectors.py from joycon2_gui.py and decky/joycon2studio/joycon2_link.py.",
        "// Do not edit by hand: run that script again after changing the desktop code.",
        "package com.joycon2studio",
        "",
        "@Suppress(\"unused\")",
        "object Generated {",
        f'    const val SERVICE_UUID = "{g.SERVICE_UUID}"',
        f'    const val INPUT_REPORT_UUID = "{g.INPUT_REPORT_UUID}"',
        f'    const val COMMAND_WRITE_UUID = "{g.COMMAND_WRITE_UUID}"',
        f'    const val COMMAND_NOTIFY_UUID = "{g.COMMAND_NOTIFY_UUID}"',
        f'    const val RUMBLE_CHAR_UUID_L = "{g.RUMBLE_CHAR_UUID["L"]}"',
        f'    const val RUMBLE_CHAR_UUID_R = "{g.RUMBLE_CHAR_UUID["R"]}"',
        f'    const val BATTERY_CHANNEL_UUID_L = "{g.BATTERY_CHANNEL["L"]}"',
        f'    const val BATTERY_CHANNEL_UUID_R = "{g.BATTERY_CHANNEL["R"]}"',
        f"    const val BATTERY_SAMPLE_MILLIS = {round(g.BATTERY_SAMPLE_SECONDS * 1000)}L",
        f"    const val BATTERY_EVERY_MILLIS = {round(g.BATTERY_EVERY_SECONDS * 1000)}L",
        f'    const val CMD_SET_LED_P1 = "{hexof(g.CMD_SET_LED_P1)}"',
        f'    const val CMD_SET_FEATURES_IMU = "{hexof(g.CMD_SET_FEATURES_IMU)}"',
        f'    const val CMD_ENABLE_FEATURES_IMU = "{hexof(g.CMD_ENABLE_FEATURES_IMU)}"',
        f'    const val CMD_READ_COLORS = "{hexof(g.CMD_READ_COLORS)}"',
        "    val SETUP_COMMANDS: List<String> = listOf(",
    ]
    lines += [f'        "{hexof(cmd)}",' for cmd in g.SETUP_COMMANDS]
    lines += [
        "    )",
        "    val NINTENDO_COMPANY_IDS: Set<Int> = setOf(" + ", ".join(f"0x{c:04X}" for c in sorted(g.NINTENDO_COMPANY_IDS)) + ")",
        f"    const val BRIDGE_PORT = {g.BRIDGE_PORT}",
    ]
    for name in BUTTONS:
        lines.append(f"    const val {name} = 0x{getattr(g, name):08X}")
    dpad = []
    for (up, down, left, right), nibble in g.DPAD_NIBBLE.items():
        mask = (1 if up else 0) | (2 if down else 0) | (4 if left else 0) | (8 if right else 0)
        dpad.append(f"0x{mask:X} to {nibble}")
    lines.append("    val DPAD_NIBBLE: Map<Int, Int> = mapOf(" + ", ".join(dpad) + ")")
    lines += [
        f"    const val LINK_MAGIC = \"{link.MAGIC.decode()}\"",
        f"    const val LINK_HS_MAGIC = \"{link.HS_MAGIC.decode()}\"",
        f"    const val LINK_VERSION = {link.VERSION}",
        f"    const val LINK_HS_X = {link.HS_X}",
        f"    const val LINK_HS_Y = {link.HS_Y}",
        f"    const val LINK_HS_CONFIRM = {link.HS_CONFIRM}",
        f"    const val LINK_HEARTBEAT = {link.HEARTBEAT}",
        f"    const val LINK_STATE = {link.STATE}",
        f"    const val LINK_RUMBLE = {link.RUMBLE}",
        f"    const val LINK_BYE = {link.BYE}",
        f"    const val LINK_PC_TO_DECK = {link.PC_TO_DECK}",
        f"    const val LINK_DECK_TO_PC = {link.DECK_TO_PC}",
        f"    const val LINK_TAG_LEN = {link.TAG_LEN}",
        f"    const val LINK_REPORT_LEN = {link.REPORT_LEN}",
        f"    const val LINK_HEADER_LEN = {link.HEADER.size}",
        f"    const val LINK_HS_HEADER_LEN = {link.HS_HEADER.size}",
        f"    const val LINK_TIMEOUT = {link.PcLink.TIMEOUT}",
        f"    const val LINK_HS_EVERY = {link.PcLink.HS_EVERY}",
        f"    const val LINK_STATE_EVERY = {link.PcLink.STATE_EVERY}",
        f"    const val LINK_DECK_TIMEOUT = {link.DeckLink.TIMEOUT}",
        f"    const val LINK_HEARTBEAT_EVERY = {link.DeckLink.HEARTBEAT_EVERY}",
        "}",
        "",
    ]
    KOTLIN_OUT.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN_OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


# ---- vectors.json ------------------------------------------------------------------------------

def point_bytes(point) -> bytes:
    return link.encode_point(point)


def vectors() -> dict:
    out = {}
    w = link.pin_scalar(PIN)
    x = scalar(b"android vector x")
    y = scalar(b"android vector y")
    B, M, N = link.B, link.M, link.N
    X = link._add(link._mul(x, B), link._mul(w, M))
    X_bytes = point_bytes(X)
    Y = link._add(link._mul(y, B), link._mul(w, N))
    Y_bytes = point_bytes(Y)
    # The Deck's side: z = y * (X - w*M); the PC's side gets the same point as x * (Y - w*N)
    z_deck = link._mul(y, link._add(link.decode_point(X_bytes), link._neg(link._mul(w, M))))
    z_pc = link._mul(x, link._add(link.decode_point(Y_bytes), link._neg(link._mul(w, N))))
    assert link._equal(z_deck, z_pc), "the two ends must agree on z"
    z_bytes = point_bytes(z_deck)
    k = link._transcript(X_bytes, Y_bytes, z_bytes, w)
    confirm_deck = link._confirm(k, b"deck", X_bytes, Y_bytes)
    confirm_pc = link._confirm(k, b"pc", X_bytes, Y_bytes)
    sid = link._session_id(k)
    keys = link.Keys(link._session_secret(k))

    out["pin"] = PIN
    out["w"] = int_hex(w, 32)
    out["B"] = hexof(point_bytes(B))
    out["M"] = hexof(point_bytes(M))
    out["N"] = hexof(point_bytes(N))
    out["x"] = int_hex(x, 32)
    out["y"] = int_hex(y, 32)
    out["X"] = hexof(X_bytes)
    out["Y"] = hexof(Y_bytes)
    out["z"] = hexof(z_bytes)
    out["k"] = hexof(k)
    out["confirm_deck"] = hexof(confirm_deck)
    out["confirm_pc"] = hexof(confirm_pc)
    out["sid"] = hexof(sid)
    out["enc"] = hexof(keys.enc)
    out["mac"] = hexof(keys.mac)
    out["hs_x_msg"] = hexof(link.HS_HEADER.pack(link.HS_MAGIC, link.VERSION, link.HS_X) + X_bytes)
    out["hs_y_msg"] = hexof(link.HS_HEADER.pack(link.HS_MAGIC, link.VERSION, link.HS_Y) + Y_bytes + confirm_deck)
    out["hs_confirm_msg"] = hexof(link.HS_HEADER.pack(link.HS_MAGIC, link.VERSION, link.HS_CONFIRM) + confirm_pc)

    # Joy-Con input reports, decoded by the desktop's own parser
    rng = random.Random(20260301)
    inputs = []
    for side in ("L", "R", "L", "R", "R"):
        data = bytes(rng.randrange(256) for _ in range(63))
        state = parse_input(side, data)
        inputs.append({
            "side": side,
            "data": hexof(data),
            "buttons": state.buttons,
            "stick_x": state.stick_x,
            "stick_y": state.stick_y,
            "gyro": [state.gyro_x, state.gyro_y, state.gyro_z],
            "accel": [state.accel_x, state.accel_y, state.accel_z],
        })
    out["inputs"] = inputs

    # The 64-byte report built from one or two decoded Joy-Cons, with the desktop's own builder
    def side_fields(state: "g.JoyConState", connected: bool) -> dict:
        return {
            "connected": connected,
            "buttons": state.buttons,
            "stick_x": state.stick_x,
            "stick_y": state.stick_y,
            "center_x": state.center_x,
            "center_y": state.center_y,
            "gyro": [state.gyro_x, state.gyro_y, state.gyro_z],
            "accel": [state.accel_x, state.accel_y, state.accel_z],
        }

    reports = []
    for label, left_on, right_on in (("both", True, True), ("left only", True, False),
                                     ("right only", False, True), ("none", False, False)):
        # a fresh decoded state for each case, so one case cannot change another
        left = parse_input("L", bytes.fromhex(inputs[0]["data"])) if left_on else g.JoyConState("L")
        right = parse_input("R", bytes.fromhex(inputs[1]["data"])) if right_on else g.JoyConState("R")
        left.connected = left_on
        right.connected = right_on
        report = bridge_report(left, right)
        reports.append({
            "label": label,
            "left": side_fields(left, left_on),
            "right": side_fields(right, right_on),
            # the desktop stamps the clock into bytes 10 and 11; the Android test passes the same value in
            "ticks": int.from_bytes(report[10:12], "little"),
            "report": hexof(report),
        })
    out["reports"] = reports

    # Packets after the handshake, sealed by the desktop's own code
    report = bytes.fromhex(reports[0]["report"])
    out["pc_state"] = hexof(link.seal(keys, link.STATE, link.PC_TO_DECK, sid, 1, report))
    out["pc_bye"] = hexof(link.seal(keys, link.BYE, link.PC_TO_DECK, sid, 2, bytes([1])))
    out["deck_heartbeat"] = hexof(link.seal(keys, link.HEARTBEAT, link.DECK_TO_PC, sid, 1, b""))
    out["deck_rumble"] = hexof(link.seal(keys, link.RUMBLE, link.DECK_TO_PC, sid, 2, bytes([0x40, 0x80])))
    tampered = bytearray(link.seal(keys, link.RUMBLE, link.DECK_TO_PC, sid, 3, bytes([0x40, 0x80])))
    tampered[-1] ^= 0x01
    out["deck_tampered"] = hexof(tampered)

    # Stick decoding and the vibration commands
    out["sticks"] = [{"bytes": [b0, b1, b2], "x": g.decode_stick(b0, b1, b2)[0], "y": g.decode_stick(b0, b1, b2)[1]}
                     for b0, b1, b2 in ((0x00, 0x00, 0x00), (0xFF, 0x0F, 0xFF), (0x34, 0x12, 0x56), (0x80, 0x80, 0x08))]
    out["vibration"] = {str(sample): hexof(g.vibration_cmd(sample)) for sample in range(8)}
    out["stick_byte"] = [{"value": v, "byte": g.stick_byte(v)} for v in (-32767, -16384, -1, 0, 1, 16384, 32767)]
    out["norm_axis"] = [{"raw": r, "center": c, "value": g.JoyCon2Manager._norm_axis(None, r, c)}
                        for r, c in ((2048, 2048), (2300, 2048), (1000, 2048), (4095, 2048), (2048, 1900))]
    return out


def main() -> None:
    write_kotlin()
    VECTOR_OUT.parent.mkdir(parents=True, exist_ok=True)
    VECTOR_OUT.write_text(json.dumps(vectors(), indent=1) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {KOTLIN_OUT.relative_to(ROOT)}")
    print(f"wrote {VECTOR_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
